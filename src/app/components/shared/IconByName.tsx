interface IconByNameProps {
  name: string;
  size?: number;
  className?: string;
}

export function IconByName({ name, size = 22, className }: IconByNameProps) {
  const Icon = ICONS[name as keyof typeof ICONS];
  if (!Icon) return null;
  return <Icon size={size} className={className} />;
}
